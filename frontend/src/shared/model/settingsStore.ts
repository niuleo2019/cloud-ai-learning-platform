const savedLanguage = localStorage.getItem('vocab-language') as AppLanguage | null;
const language = ref<AppLanguage>(savedLanguage === 'zh' || savedLanguage === 'en' ? savedLanguage : 'en');
const savedThemeMode = localStorage.getItem('vocab-theme-mode') as ThemeMode | null;
const themeMode = ref<ThemeMode>(savedThemeMode === 'manual' ? 'manual' : 'auto');

function isNightTime(date = new Date()) {
  const hour = date.getHours();
  return hour >= 18 || hour < 6;
}

const savedDarkMode = localStorage.getItem('vocab-dark-mode');
const darkMode = ref(themeMode.value === 'manual' ? savedDarkMode === 'true' : isNightTime());

function applyTheme() {
  document.documentElement.classList.toggle('theme-dark', darkMode.value);
}

function syncThemeWithTime() {
  if (themeMode.value === 'manual') return;
  darkMode.value = isNightTime();
  applyTheme();
}

watch(
  language,
  (value) => {
    localStorage.setItem('vocab-language', value);
  },
  { immediate: true }
);

watch(
  darkMode,
  (value) => {
    if (themeMode.value === 'manual') {
      localStorage.setItem('vocab-dark-mode', String(value));
    }
    applyTheme();
  },
  { immediate: true }
);

watch(
  themeMode,
  (value) => {
    localStorage.setItem('vocab-theme-mode', value);
    if (value === 'auto') {
      syncThemeWithTime();
    } else {
      localStorage.setItem('vocab-dark-mode', String(darkMode.value));
    }
  },
  { immediate: true }
);

window.setInterval(syncThemeWithTime, 60_000);

export function useSettingsStore() {
  return {
    language,
    darkMode,
    themeMode,
    t(key: TranslationKey) {
      return messages[language.value][key] || key;
    },
    setLanguage(value: AppLanguage) {
      language.value = value;
    },
    setDarkMode(value: boolean) {
      themeMode.value = 'manual';
      darkMode.value = value;
    },
    setThemeMode(value: ThemeMode) {
      themeMode.value = value;
    }
  };
}
