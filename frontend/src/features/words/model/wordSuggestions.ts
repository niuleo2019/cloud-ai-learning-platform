export function getWordSuggestions(input: string, limit = 6) {
  const keyword = input.trim().toLowerCase();
  if (!keyword) return [];

  return academicWords
    .filter((word) => word.startsWith(keyword) && word !== keyword)
    .slice(0, limit);
}
